#!/usr/bin/env node
/* Generates assets/pack-hashes.js — the expected SHA-256 of every course pack.
 *
 * The app compares each downloaded pack against these values, so a tampered
 * first download is rejected instead of being pinned as trusted.
 *
 *   node scripts/hash-packs.mjs           # regenerate
 *   node scripts/hash-packs.mjs --check   # fail if the file is stale (CI)
 *
 * Requires Node 18 or newer.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const packsDir = join(root, 'data', 'packs');
const outFile = join(root, 'assets', 'pack-hashes.js');
const checkOnly = process.argv.includes('--check');

const normalize = s => String(s).replace(/\r\n/g, '\n');

function fail(message) {
  console.error('✗ ' + message);
  process.exit(1);
}

/* ---- read the packs ---- */
let files;
try {
  files = (await readdir(packsDir)).filter(f => f.endsWith('.json')).sort();
} catch (e) {
  fail(`cannot read ${packsDir} (${e.code}). Run this from the repository root.`);
}
if (!files.length) fail(`no .json packs found in ${packsDir}`);

const entries = [];
for (const file of files) {
  const bytes = await readFile(join(packsDir, file));
  const id = file.replace(/\.json$/, '');
  try {
    JSON.parse(bytes.toString('utf8'));
  } catch (e) {
    fail(`${file} is not valid JSON — fix it before hashing: ${e.message}`);
  }
  entries.push([id, createHash('sha256').update(bytes).digest('hex')]);
}

/* ---- build the output ---- */
const body = `/* GENERATED by scripts/hash-packs.mjs — do not edit by hand.
 * Expected SHA-256 of each course pack. The app refuses to render a pack whose
 * content does not match, so a tampered first download is detected rather than
 * pinned as trusted. Regenerate after editing anything in data/packs/:
 *
 *   node scripts/hash-packs.mjs
 */
window.PACK_HASHES = {
${entries.map(([id, hash]) => `  ${id}: '${hash}'`).join(',\n')}
};
`;

/* ---- write or verify ---- */
if (checkOnly) {
  let current;
  try {
    current = await readFile(outFile, 'utf8');
  } catch (e) {
    fail('assets/pack-hashes.js is missing. Run: node scripts/hash-packs.mjs');
  }
  if (normalize(current) !== normalize(body)) {
    console.error('✗ assets/pack-hashes.js is out of date.');
    console.error('  Run: node scripts/hash-packs.mjs');
    console.error('  Expected:');
    for (const [id, hash] of entries) console.error(`    ${id.padEnd(8)} ${hash}`);
    process.exit(1);
  }
  console.log('✓ pack hashes match data/packs/');
} else {
  await writeFile(outFile, body, 'utf8');
  console.log('✓ wrote assets/pack-hashes.js');
  for (const [id, hash] of entries) console.log(`  ${id.padEnd(8)} ${hash}`);
  console.log('\nNow commit it:  git add assets/pack-hashes.js && git commit -m "chore: generate pack hashes"');
}

