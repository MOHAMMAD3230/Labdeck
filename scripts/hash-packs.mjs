#!/usr/bin/env node
/* Generates assets/pack-hashes.js — the expected SHA-256 of every course pack.
 *
 * The app compares each downloaded pack against these values, so a tampered
 * first download is rejected instead of being pinned as trusted.
 *
 *   node scripts/hash-packs.mjs           # regenerate
 *   node scripts/hash-packs.mjs --check   # fail if the file is stale (CI)
 *   node scripts/hash-packs.mjs --help
 *
 * Requires Node 18 or newer.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const packsDir = join(root, 'data', 'packs');
const outDir = join(root, 'assets');
const outFile = join(outDir, 'pack-hashes.js');

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');

const normalize = s => String(s).replace(/\r\n/g, '\n');

function fail(message, hint) {
  console.error('✗ ' + message);
  if (hint) console.error('  ' + hint);
  process.exit(1);
}

if (args.includes('--help') || args.includes('-h')) {
  console.log(`Usage: node scripts/hash-packs.mjs [--check]

  (no flag)  regenerate assets/pack-hashes.js from data/packs/*.json
  --check    exit 1 if the committed file does not match the packs
  --help     show this message`);
  process.exit(0);
}

/* ---- read the packs ---- */
let files;
try {
  files = (await readdir(packsDir)).filter(f => f.endsWith('.json')).sort();
} catch (e) {
  fail(`cannot read ${packsDir} (${e.code})`, 'Run this from the repository root.');
}

if (!files.length) {
  fail(`no .json packs found in ${packsDir}`, 'Expected files like data/packs/linux.json');
}

const entries = [];
for (const file of files) {
  const bytes = await readFile(join(packsDir, file));
  const id = file.replace(/\.json$/, '');

  let parsed;
  try {
    parsed = JSON.parse(bytes.toString('utf8'));
  } catch (e) {
    fail(`${file} is not valid JSON — fix it before hashing`, e.message);
  }
  if (!parsed || typeof parsed !== 'object' || !parsed.lessons || typeof parsed.lessons !== 'object') {
    fail(`${file} has no "lessons" object`, 'A pack must look like { "course": "...", "lessons": { ... } }');
  }

  const hash = createHash('sha256').update(bytes).digest('hex');
  if (!/^[a-f0-9]{64}$/.test(hash)) fail(`unexpected hash for ${file}`);

  entries.push({ id, hash, bytes: bytes.length, lessons: Object.keys(parsed.lessons).length });
}

/* ---- build the output ---- */
const body = `/* GENERATED by scripts/hash-packs.mjs — do not edit by hand.
 * Expected SHA-256 of each course pack. The app refuses to render a pack whose
 * content does not match, so a tampered first download is detected rather than
 * pinned as trusted. Regenerate after editing anything in data/packs/:
 *
 *   node scripts/hash-packs.mjs
 */
window.PACK_HASHES = {
${entries.map(e => `  ${e.id}: '${e.hash}'`).join(',\n')}
};
`;

/* ---- write or verify ---- */
if (checkOnly) {
  let current;
  try {
    current = await readFile(outFile, 'utf8');
  } catch (e) {
    fail('assets/pack-hashes.js is missing', 'Run: node scripts/hash-packs.mjs');
  }

  if (normalize(current) !== normalize(body)) {
    console.error('✗ assets/pack-hashes.js is out of date.');
    console.error('  Run: node scripts/hash-packs.mjs\n');
    console.error('  Expected:');
    for (const e of entries) console.error(`    ${e.id.padEnd(12)} ${e.hash}`);
    process.exit(1);
  }

  console.log(`✓ pack hashes match data/packs/ (${entries.length} packs)`);
  for (const e of entries) console.log(`    ${e.id.padEnd(12)} ${e.hash.slice(0, 16)}…`);
} else {
  await mkdir(outDir, { recursive: true });
  await writeFile(outFile, body, 'utf8');

  console.log(`✓ wrote assets/pack-hashes.js (${entries.length} packs)`);
  for (const e of entries) {
    console.log(`    ${e.id.padEnd(12)} ${e.hash}`);
    console.log(`    ${' '.repeat(12)} ${e.lessons} lessons, ${(e.bytes / 1024).toFixed(1)} KB`);
  }
  console.log('\nCommit it:  git add assets/pack-hashes.js && git commit -m "chore: regenerate pack hashes"');
}
